CREATE TABLE IF NOT EXISTS public.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    document_id VARCHAR(32) NOT NULL UNIQUE,
    risk_tier VARCHAR(16) NOT NULL DEFAULT 'LOW'
        CHECK (risk_tier IN ('LOW', 'MEDIUM', 'HIGH')),
    created_at TIMESTAMP(3) NOT NULL DEFAULT (timezone('utc', clock_timestamp()))
);

CREATE TABLE IF NOT EXISTS public.accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL
        REFERENCES public.customers (customer_id) ON DELETE RESTRICT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'BLOCKED', 'CLOSED')),
    balance NUMERIC(15, 2) NOT NULL DEFAULT 0.00
        CHECK (balance >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'BRL',
    updated_at TIMESTAMP(3) NOT NULL DEFAULT (timezone('utc', clock_timestamp()))
);

CREATE TABLE IF NOT EXISTS public.cards (
    card_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL
        REFERENCES public.accounts (account_id) ON DELETE RESTRICT,
    card_fingerprint VARCHAR(64) NOT NULL UNIQUE,
    last4 VARCHAR(4) NOT NULL CHECK (char_length(last4) = 4),
    brand VARCHAR(16) NOT NULL
        CHECK (brand IN ('VISA', 'MASTERCARD', 'ELO')),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'FROZEN', 'CANCELLED')),
    created_at TIMESTAMP(3) NOT NULL DEFAULT (timezone('utc', clock_timestamp()))
);

CREATE TABLE IF NOT EXISTS public.merchants (
    merchant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category_code VARCHAR(10) NOT NULL,
    country VARCHAR(2) NOT NULL DEFAULT 'BR',
    risk_level VARCHAR(16) NOT NULL DEFAULT 'LOW'
        CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH'))
);

CREATE TABLE IF NOT EXISTS public.transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL
        REFERENCES public.accounts (account_id) ON DELETE RESTRICT,
    card_id BIGINT NOT NULL
        REFERENCES public.cards (card_id) ON DELETE RESTRICT,
    merchant_id BIGINT NOT NULL
        REFERENCES public.merchants (merchant_id) ON DELETE RESTRICT,
    amount NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'BRL',
    status VARCHAR(16) NOT NULL
        CHECK (status IN ('APPROVED', 'DECLINED', 'PENDING')),
    channel VARCHAR(16) NOT NULL
        CHECK (channel IN ('POS', 'ECOMMERCE', 'CONTACTLESS')),
    created_at TIMESTAMP(3) NOT NULL DEFAULT (timezone('utc', clock_timestamp()))
);

-- Índices cirúrgicos para chaves estrangeiras e padrões de consulta analítica/transacional
CREATE INDEX IF NOT EXISTS idx_accounts_customer_id
    ON public.accounts (customer_id);

CREATE INDEX IF NOT EXISTS idx_cards_account_id
    ON public.cards (account_id);

CREATE INDEX IF NOT EXISTS idx_transactions_account_created
    ON public.transactions (account_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_transactions_card_created
    ON public.transactions (card_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_transactions_merchant_id
    ON public.transactions (merchant_id);

-- REPLICA IDENTITY FULL: garante campo `before` completo em UPDATE e DELETE no Debezium
ALTER TABLE public.customers REPLICA IDENTITY FULL;
ALTER TABLE public.accounts REPLICA IDENTITY FULL;
ALTER TABLE public.cards REPLICA IDENTITY FULL;
ALTER TABLE public.merchants REPLICA IDENTITY FULL;
ALTER TABLE public.transactions REPLICA IDENTITY FULL;

-- Publicação explícita pré-criada (permite publication.autocreate.mode=disabled no conector)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication WHERE pubname = 'dbz_publication'
    ) THEN
        CREATE PUBLICATION dbz_publication FOR TABLE
            public.customers,
            public.accounts,
            public.cards,
            public.merchants,
            public.transactions;
    END IF;
END
$$;
